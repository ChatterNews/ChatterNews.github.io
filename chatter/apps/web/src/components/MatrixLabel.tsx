export function MatrixLabel({ text }: { text: 'EXPAND VIEW' | 'SHOW ROOMS' }) {
  return <svg className="spiral-matrix-label" viewBox={`0 0 ${text.length * 6 - 1} 7`} aria-hidden="true">
    {[...text].flatMap((letter, index) => (letters[letter] ?? []).flatMap((row, y) =>
      [...row].flatMap((lit, x) => lit === '1'
        ? [<circle key={`${index}-${x}-${y}`} cx={index * 6 + x + .5} cy={y + .5} r={.38} />]
        : [])))}
  </svg>;
}
